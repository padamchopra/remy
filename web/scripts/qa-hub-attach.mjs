import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { chromiumPath } from './chromium.mjs';
import { readFileSync } from 'node:fs';
const info = JSON.parse(readFileSync(process.env.QA_SESSION, 'utf8'));
const browser = await chromium.launch({ executablePath: chromiumPath() });
const context = await browser.newContext({ viewport: {width:1280,height:900} });
context.setDefaultTimeout(15000);
const local = await context.newPage();
try {
  await local.goto(`${process.env.QA_LOCAL_URL}/#/settings/devices`);
  await local.getByRole('button', {name:'Attach this Mac', exact:true}).click();
  await local.getByRole('button', {name:'Advanced connection settings', exact:true}).click();
  await local.getByLabel('Remy address').fill(info.hubUrl);
  await local.getByRole('button', {name:'Continue', exact:true}).click();
  await local.getByRole('link', {name:'Approve in your browser'}).waitFor();
  const code = await local.getByLabel('Computer authorization code').innerText();
  const opening = context.waitForEvent('page');
  await local.getByRole('link', {name:'Approve in your browser'}).click();
  const web = await opening;
  await web.getByLabel('Email', {exact:true}).fill(`mac-setup-${Date.now()}@example.test`);
  const email = await web.getByLabel('Email', {exact:true}).inputValue();
  await web.getByRole('button', {name:'Email sign-in link'}).click();
  await web.getByText('Check your email for your sign-in link.', {exact:true}).waitFor();
  const mail = await (await fetch(`${info.controlUrl}/mail?email=${encodeURIComponent(email)}`, {headers:{authorization:`Bearer ${info.controlToken}`}})).json();
  await web.goto(mail.url);
  await web.getByRole('heading', {name:'Approve your computer'}).waitFor();
  assert.equal(await web.getByLabel('Computer authorization code').innerText(), code);
  await web.getByRole('button', {name:'Approve computer',exact:true}).click();
  await web.getByRole('heading', {name:'Return to your Mac'}).waitFor();
  await web.getByRole('button', {name:'Done',exact:true}).click();
  await web.getByRole('button', {name:'Choose personal or organization'}).click();
  await web.getByRole('menuitem', {name:'Create organization'}).click();
  await web.getByLabel('Name', {exact:true}).fill('Studio setup');
  await web.getByRole('dialog').getByRole('button', {name:'Create organization',exact:true}).click();
  await web.getByRole('dialog').waitFor({state:'hidden'});
  await local.getByRole('button', {name:'Choose account',exact:true}).click();
  await local.getByRole('combobox', {name:'Attach to account'}).click();
  await local.getByRole('option', {name:'Studio setup',exact:true}).click();
  await local.getByRole('button', {name:'Finish connecting',exact:true}).click();
  await local.getByRole('dialog').waitFor({state:'hidden'});
  await local.getByRole('button', {name:'Detach this Mac',exact:true}).waitFor();
  await web.getByRole('button', {name:'Computers',exact:true}).first().click();
  await web.getByRole('button', {name:'Continue to your threads',exact:true}).waitFor();
  console.log('PASS: current local daemon and web app complete the Mac approval handoff; matching code survives sign-in and the connected computer arrives live.');
} catch(e) {
  console.error((await local.locator('body').innerText()).replace(/[A-Z0-9]{4}-[A-Z0-9]{4}/g,'[code]').slice(-2000));
  throw e;
} finally { await context.close(); await browser.close(); }
