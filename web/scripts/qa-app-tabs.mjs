import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { chromium } from 'playwright-core';
import { chromiumPath } from './chromium.mjs';

const session = JSON.parse(readFileSync(process.env.QA_SESSION, 'utf8'));
const base = process.env.QA_WEB_URL ?? session.hubUrl;
const output = process.env.QA_ARTIFACTS ?? '/tmp/remy-pr-artifacts/app-tabs';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (process.platform === 'darwin' ? chromiumPath() : chromium.executablePath()), headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: output, size: { width: 1440, height: 900 } } });
await context.addCookies([{ name: 'remy_session', value: session.tokens.ada, url: base, httpOnly: true, sameSite: 'Lax' }]);
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
  await page.goto(`${base}/threads/${session.threadId}`);
  const tabs = page.getByRole('tablist', { name: 'Open tabs' }).first();
  await tabs.waitFor({ timeout: 5000 });
  assert.equal(await tabs.getByRole('tab').count(), 1);
  await page.getByRole('button', { name: 'New tab' }).click();
  assert.equal(await tabs.getByRole('tab').count(), 2);
  await page.getByRole('button', { name: 'Pull requests', exact: true }).first().click();
  await tabs.getByRole('tab', { name: 'Pull requests' }).waitFor();
  await page.waitForTimeout(350);
  await page.getByRole('button', { name: 'New tab' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).first().click();
  await tabs.getByRole('tab', { name: 'General settings' }).waitFor();
  await page.waitForTimeout(350);
  assert.equal(await tabs.getByRole('tab').count(), 3);
  await tabs.getByRole('tab', { name: 'General settings' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Split left and right' }).click();
  assert.equal(await page.locator('section[aria-label$="pane"]:visible').count(), 2);
  assert.equal(await tabs.getByRole('tab').count(), 3);
  await page.screenshot({ path: `${output}/split-settings.png` });
  await page.waitForTimeout(700);
  await tabs.getByRole('tab', { name: 'General settings' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Unsplit' }).click();
  await tabs.getByRole('tab', { name: /Thread|Prepare/ }).first().click();
  await tabs.getByRole('tab', { name: /Thread|Prepare/ }).first().click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Split top and bottom' }).click();
  assert.equal(await page.locator('section[aria-label$="pane"]:visible').count(), 2);
  assert.match(new URL(page.url()).pathname, /pull-requests/);
  assert.equal(await page.getByRole('button', { name: 'Pull requests', exact: true }).first().getAttribute('data-active'), 'true');
  await page.locator('section[aria-label="Thread pane"]').first().click({ position: { x: 10, y: 110 } });
  assert.match(new URL(page.url()).pathname, /threads/);
  assert.equal(await page.getByRole('button', { name: 'Threads', exact: true }).first().getAttribute('data-active'), 'true');
  await page.screenshot({ path: `${output}/split-tabs.png` });
  await page.waitForTimeout(700);
  await page.reload();
  await tabs.getByRole('tab', { name: 'Pull requests' }).waitFor();
  assert.equal(await tabs.getByRole('tab').count(), 3);
  assert.equal(await page.locator('section[aria-label$="pane"]:visible').count(), 2);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('section[aria-label$="pane"]:visible').count(), 1);
  await page.screenshot({ path: `${output}/phone-tabs.png` });
  assert.deepEqual(errors, []);
  console.log('App tabs QA passed: three destinations, both split directions, focus, reload, and phone layout.');
} finally {
  const video = page.video();
  await context.close();
  if (video) copyFileSync(await video.path(), `${output}/tab-flow.webm`);
  await browser.close();
}
