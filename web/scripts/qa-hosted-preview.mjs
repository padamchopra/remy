import {chromium} from 'playwright-core';
import {chromiumPath} from './chromium.mjs';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const info=JSON.parse(readFileSync(process.env.QA_SESSION,'utf8'));
const url=process.env.QA_PREVIEW_URL || 'http://127.0.0.1:5176';
const browser=await chromium.launch({executablePath:chromiumPath()});
try {
 const context=await browser.newContext();
 const page=await context.newPage();
 page.setDefaultTimeout(15000);
 page.on('pageerror', error=>console.error(error.message));
 await page.goto(url);
 await page.screenshot({path:'/tmp/remy-preview-signin-check.png'});
 await page.getByRole('button',{name:'Sign in with Remy'}).click();
 const approvalUrl=await page.getByRole('link',{name:'Approve in Remy'}).getAttribute('href');
 const auth=await browser.newContext();
 await auth.addCookies([{name:'remy_session',value:info.tokens.ada,url:info.hubUrl,httpOnly:true,sameSite:'Lax'}]);
 const approval=await auth.newPage();await approval.goto(approvalUrl);
 await approval.getByRole('button',{name:'Approve preview',exact:true}).click();
 await approval.getByRole('heading',{name:'Return to your preview'}).waitFor();
 await page.getByRole('button',{name:'Finish signing in'}).click();
 await page.getByRole('button',{name:'Choose personal or organization'}).waitFor();
 await page.goto(`${url}/#/settings/devices?organization=${info.organizationId}`);
 await page.locator(`[data-computer-id="${info.computerId}"]`).waitFor();
 await page.getByRole('button',{name:'Edit computer',exact:true}).click();
 const input=page.getByRole('textbox',{name:'Name',exact:true});
 const original=await input.inputValue();
 await input.fill('Preview connected Mac');
 await page.getByRole('button',{name:'Save computer'}).click();
 await page.getByRole('button',{name:'Preview connected Mac',exact:true}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Preview connected Mac',exact:true}).waitFor();
 await page.getByRole('button',{name:'Edit computer',exact:true}).click();
 await page.getByRole('textbox',{name:'Name',exact:true}).fill(original);
 await page.getByRole('button',{name:'Save computer'}).click();
 const result=await page.evaluate(async()=>{const response=await fetch('/api/profile');return response.status;});
 assert.equal(result,200);
 await page.screenshot({path:'/tmp/remy-preview-authenticated.png'});
 await page.evaluate(()=>fetch('/api/sessions/current',{method:'DELETE'}));
 await page.reload();
 await page.getByRole('button',{name:'Sign in with Remy'}).waitFor();
 console.log('Hosted preview QA passed: approval, authenticated write, live list update, reload, and sign-out.');
} finally {await browser.close();}
